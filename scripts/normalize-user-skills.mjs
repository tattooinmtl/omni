#!/usr/bin/env node
// Normalize user-installed skill files for the Omni Agent harness.
//
// For each <user-skill>/SKILL.md under ~/.kimi-code/skills and ~/.agents/skills:
//   1. Collapse YAML block-scalar descriptions (`description: |` / `>`) into
//      single-line strings so the omni frontmatter parser reads them correctly.
//   2. Insert an omni-harness banner directly under the frontmatter so each
//      file is visibly tagged as registered under the omni-present agent.
//   3. Leave an existing banner alone (idempotent).
//
// Run with no args to process every discovered skill; pass skill names to
// target specific ones.
//
//   node scripts/normalize-user-skills.mjs             # all
//   node scripts/normalize-user-skills.mjs fullstack-dev rust-guidelines
//
// Reports a JSON summary on stdout and exits non-zero if any file is unreadable.

import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const ROOTS = [
  path.join(os.homedir(), ".kimi-code", "skills"),
  path.join(os.homedir(), ".agents", "skills"),
];

const BANNER = [
  "<!-- generated by omni-harness: this skill is registered with the omni-present agent. Invoke via /<skill-name> in the Omni CLI. -->",
  "",
].join("\n");

function splitFrontmatter(text) {
  // Leading `---` ... `---` block (Unix or CRLF line endings).
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return null;
  return { raw: m[1], body: m[2], eol: text.includes("\r\n") ? "\r\n" : "\n" };
}

function normalizeDescription(raw) {
  const lines = raw.split(/\r?\n/);
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const kv = line.match(/^(\s*)([\w-]+):\s*(.*)$/);
    if (!kv) { out.push(line); i++; continue; }
    const indent = kv[1] || "";
    const key = kv[2];
    const val = kv[3];
    if (key === "description" && (val === "|" || val === "|-" || val === ">" || val === ">-")) {
      // Block of indented (or blank) lines follows.
      const block = [];
      i++;
      while (i < lines.length) {
        const next = lines[i];
        if (next === "" || /^\s/.test(next)) {
          block.push(next.replace(/^\s+/, ""));
          i++;
        } else break;
      }
      const joined = block.join(" ").replace(/\s+/g, " ").trim();
      out.push(`${indent}description: ${joined}`);
    } else {
      out.push(line);
      i++;
    }
  }
  return out.join("\n");
}

function bannerAlreadyPresent(body) {
  return /<!--\s*generated by omni-harness/i.test(body.split(/\r?\n/, 6).join("\n"));
}

function processFile(skillFile) {
  const original = fs.readFileSync(skillFile, "utf8");
  const parts = splitFrontmatter(original);
  if (!parts) return { skillFile, status: "no-frontmatter" };

  const normalizedRaw = normalizeDescription(parts.raw);
  const changed = normalizedRaw !== parts.raw;

  // Add the banner after the closing `---`, before any body content.
  let body = parts.body;
  // Strip any existing banner we previously inserted so we don't duplicate.
  body = body.replace(/^\s*<!--\s*generated by omni-harness[\s\S]*?-->\s*\r?\n?/, "");
  body = BANNER + body.replace(/^\r?\n+/, "");

  const rebuilt = `---\n${normalizedRaw}\n---\n${body}`;
  if (rebuilt === original) return { skillFile, status: "ok" };

  fs.writeFileSync(skillFile, rebuilt, "utf8");
  return { skillFile, status: changed ? "normalized+banner" : "banner" };
}

function listSkills(roots, onlyFilter) {
  const out = [];
  for (const root of roots) {
      if (!fs.existsSync(root)) continue;
      let entries;
      try { entries = fs.readdirSync(root, { withFileTypes: true }); }
      catch { continue; }
      for (const e of entries) {
        if (!e.isDirectory()) continue;
        if (onlyFilter && !onlyFilter.has(e.name)) continue;
        const skillFile = path.join(root, e.name, "SKILL.md");
        if (fs.existsSync(skillFile)) out.push(skillFile);
      }
  }
  return out;
}

const only = process.argv.slice(2);
const onlySet = only.length ? new Set(only) : null;
const files = listSkills(ROOTS, onlySet);

const results = [];
let errors = 0;
for (const f of files) {
  try {
    results.push(processFile(f));
  } catch (e) {
    results.push({ skillFile: f, status: "error", error: e.message });
    errors++;
  }
}

const counts = results.reduce((acc, r) => {
  acc[r.status] = (acc[r.status] || 0) + 1;
  return acc;
}, {});

console.log(JSON.stringify({ counts, total: results.length, errors, results }, null, 2));
process.exit(errors ? 1 : 0);